export function getQuestionsByGrade(grade: GradeLevel): QuestionItem[] {
  return PRACTICE_QUESTIONS.filter(q => q.grade === Number(grade));
}

export function getQuestionsByChapter(chapterId: string): QuestionItem[] {
  return PRACTICE_QUESTIONS.filter(q => q.chapterId === chapterId);
}

export function filterQuestions(
  grade: GradeLevel,
  chapterId?: string,
  difficulty?: DifficultyLevel
): QuestionItem[] {
  return PRACTICE_QUESTIONS.filter(q => {
    if (q.grade !== Number(grade)) return false;
    if (chapterId && chapterId !== 'all' && q.chapterId !== chapterId) return false;
    if (difficulty && q.difficulty !== difficulty) return false;
    return true;
  });
}
