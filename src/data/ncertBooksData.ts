export function getNcertBookByGrade(grade: number): NcertBook {
  return NCERT_BOOKS_DATA[grade] || NCERT_BOOKS_DATA[10];
}

export function getNcertChapterPdf(grade: number, chapterNumber: number): NcertChapterPdf | undefined {
  const book = getNcertBookByGrade(grade);
  return book.chapters.find(ch => ch.chapterNumber === chapterNumber);
}
